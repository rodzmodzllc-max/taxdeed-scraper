#!/usr/bin/env python3
"""Build the register-to-code source-rights reconciliation (2026-10-16).

    python3 scripts/build_source_rights_report.py           # write
    python3 scripts/build_source_rights_report.py --check   # fail if stale

Reads the 84-row disposition register (data/audit/source_register_2026-10-12.csv),
the register-to-code map (data/audit/register_code_map.csv), the county
source registry and the permission records, and writes:

  * data/audit/source_rights_reconciliation.json - every row, the operations
    the permission engine allows at each place of its scope, and every finding;
  * docs/audit/source-rights-reconciliation.md - the per-source table.

The permission engine is evaluated as of AS_OF (a fixed date, so the output
is reproducible; a record that expires after it reads as it will that day).
No network, no database. The register is an audit baseline, never an
authorization: nothing here grants anything. Contact details and outreach
correspondence from the register are deliberately left out of both outputs.
"""
from __future__ import annotations

import argparse
import json
import sys
from datetime import date
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO))

from harvesters.governance import source_rights as R  # noqa: E402

AS_OF = date(2026, 10, 16)
JSON_OUT = REPO / "data" / "audit" / "source_rights_reconciliation.json"
MD_OUT = REPO / "docs" / "audit" / "source-rights-reconciliation.md"

# The fix and the tests per finding kind / decision class. Dispositions for
# the unsafe paths live in docs/source-rights-enforcement.md.
FIX_FOR = {
    "EXCEEDS_CEILING": "Owner decision: narrow the permission records to the register decision (see docs/source-rights-enforcement.md)",
    "NO_PERMISSION_RECORD": "Keep unwired; add a record (deny by default) before any code reads it",
    "CLIENT_SIDE_NO_RECORD": "Owner decision: record the provider terms; the browser loads it outside the permission engine",
    "NO_CODE_SOURCE": "None - nothing reads it",
}
TESTS_FOR = {
    "ENABLED": "test_source_rights.py::test_every_mapped_row_is_evaluated_per_place",
    "MANUAL_ONLY": "test_source_rights.py::test_every_mapped_row_is_evaluated_per_place",
    "ADMIN_ONLY": "test_source_rights.py::test_admin_only_sources_never_allow_display",
    "LINKS_ONLY": "test_source_rights.py::test_link_only_allows_no_copy",
    "BLOCKED": "test_source_rights.py::test_hard_blocked_vendors_allow_nothing",
    "DECISION_REQUIRED": "test_source_rights.py::test_proxy_fallback_is_denied_on_interim_permission",
    "CLIENT_SIDE": "test_source_rights.py::test_client_side_providers_are_reported",
}


def _visibility(row: dict) -> str:
    allowed = row["allowed"]
    if any(k.endswith(":display") for k in allowed):
        return "customer display allowed (interim)" if all(
            "INTERIM" in v for k, v in allowed.items() if k.endswith(":display")) else "customer display allowed"
    if any(k.endswith(":store") for k in allowed):
        return "stored, not displayed"
    if any(k.endswith(":enrich") for k in allowed):
        return "enrichment only"
    if any(k.endswith(":link") for k in allowed):
        return "link only"
    return "nothing allowed"


def _ops(row: dict) -> str:
    if not row["allowed"]:
        return "none"
    out = []
    for key, bases in row["allowed"].items():
        sid, op = key.rsplit(":", 1)
        tag = "/".join(b[0] for b in bases)
        out.append(f"{op}({tag})" if len(row["code_source_ids"]) == 1 else f"{sid}.{op}({tag})")
    return ", ".join(out)


def _cell(text: str, n: int = 140) -> str:
    t = " ".join(str(text or "").split()).replace("|", "/")
    return t if len(t) <= n else t[: n - 1] + "…"


def build() -> tuple[str, str]:
    data = R.reconcile(today=AS_OF)
    rows = data["rows"]
    findings = data["findings"]
    payload = {
        "as_of": AS_OF.isoformat(),
        "note": ("Register-to-code reconciliation. The register is an audit baseline, not an authorization. "
                 "Operations are what data/source_permissions.csv allows on AS_OF, per county and dataset."),
        "summary": {
            "register_rows": len(rows),
            "by_match_type": _count(r["match_type"] for r in rows),
            "by_decision_class": _count(r["decision_class"] for r in rows),
            "findings_by_kind": _count(f["kind"] for f in findings),
        },
        "rows": [{k: r[k] for k in ("register_id", "code_source_ids", "match_type", "decision_class", "scope",
                                    "places", "allowed", "findings")} for r in rows],
        "findings": findings,
    }
    js = json.dumps(payload, indent=1, sort_keys=True) + "\n"

    lines = [
        "# Source rights reconciliation",
        "",
        f"Generated by `scripts/build_source_rights_report.py` as of {AS_OF.isoformat()} (`--check` pinned). "
        "Do not edit by hand.",
        "",
        "Each of the 84 rows of the 2026-10-12 disposition register is mapped to the code source ids "
        "(`data/audit/register_code_map.csv`). The operations column is what the permission engine "
        "(`data/source_permissions.csv`) allows **at each county of the row's scope** for the row's datasets: "
        "D = documented (published licence or written permission), I = interim (grandfathered practice or "
        "internal risk acceptance - never permission), L = link only. `discover` is governed by the discovery "
        "guard and is not listed. The register is an audit baseline, not an authorization; contact details and "
        "outreach correspondence are deliberately left out.",
        "",
        "## Findings",
        "",
        "| Kind | Register row | Code source | Operations | Places | Fix |",
        "|---|---|---|---|---|---|",
    ]
    for f in findings:
        places = f["places"]
        where = (", ".join(places) if len(places) <= 4 else f"{len(places)} counties ({', '.join(places[:3])}, …)") or "-"
        lines.append(f"| {f['kind']} | {f['register_id'] or '-'} | {f['source_id'] or '-'} | "
                     f"{', '.join(f['operations']) or '-'} | {where} | {_cell(FIX_FOR.get(f['kind'], ''), 120)} |")
    lines += [
        "",
        "## Summary",
        "",
        f"- Register rows: {len(rows)}",
        "- By match type: " + ", ".join(f"{k} {v}" for k, v in payload["summary"]["by_match_type"].items()),
        "- By register decision: " + ", ".join(f"{k} {v}" for k, v in payload["summary"]["by_decision_class"].items()),
        "- Findings: " + (", ".join(f"{k} {v}" for k, v in payload["summary"]["findings_by_kind"].items()) or "none"),
        "",
        "## Per-source table",
        "",
        "| Register row | Code source ids (match) | Provider / data owner | Scope | Data types | Ingestion status | "
        "Customer visibility (code) | Rights status (register) | Register decision | Code allows | Finding / fix | Tests |",
        "|---|---|---|---|---|---|---|---|---|---|---|---|",
    ]
    for r in rows:
        fx = "; ".join(f"{f['kind']}" for f in r["findings"]) or "none"
        if r["findings"]:
            fx += " - " + FIX_FOR.get(r["findings"][0]["kind"], "")
        sids = ", ".join(r["code_source_ids"]) or "-"
        lines.append(
            f"| {r['register_id']} | {sids} ({r['match_type']}) | {_cell(r['provider'], 90)} | {_cell(r['coverage'], 60)} | "
            f"{_cell(r['data_types'], 80)} | {_cell(r['implementation_status'], 70)} | {_visibility(r)} | "
            f"{_cell(r['legal_status'], 60)} | {r['decision_class']}: {_cell(r['decision'], 70)} | {_cell(_ops(r), 120)} | "
            f"{_cell(fx, 140)} | {TESTS_FOR.get(r['decision_class'], 'test_source_rights.py::test_reconciliation_report_is_current')} |")
    return js, "\n".join(lines) + "\n"


def _count(it) -> dict:
    out: dict[str, int] = {}
    for k in it:
        out[k] = out.get(k, 0) + 1
    return dict(sorted(out.items()))


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--check", action="store_true", help="fail if the outputs are stale")
    args = ap.parse_args(argv)
    js, md = build()
    if args.check:
        stale = [p for p, t in ((JSON_OUT, js), (MD_OUT, md)) if not p.exists() or p.read_text(encoding="utf-8") != t]
        for p in stale:
            print(f"{p.relative_to(REPO)} is stale - run scripts/build_source_rights_report.py", file=sys.stderr)
        if not stale:
            print("source rights reconciliation is current")
        return 1 if stale else 0
    MD_OUT.parent.mkdir(parents=True, exist_ok=True)
    JSON_OUT.write_text(js, encoding="utf-8")
    MD_OUT.write_text(md, encoding="utf-8")
    print(f"wrote {JSON_OUT.relative_to(REPO)} and {MD_OUT.relative_to(REPO)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
