def fmt_date(iso: str) -> str:
    """'2026-11-02' -> 'Nov 2, 2026'."""
    d = datetime.date.fromisoformat(iso[:10])
    return f"{d.strftime('%b')} {d.day}, {d.year}"


def mostly_caps(t: str) -> bool:
    letters = re.sub(r"[^A-Za-z]", "", t or "")
    return len(letters) >= 20 and sum(c.isupper() for c in letters) / len(letters) > 0.6


def journey(doc: dict) -> dict:
    j = doc.get("journey") or {}
    return {"steps": j.get("steps") or list(DEFAULT_STEPS), "map": j.get("map") or {},
            "ledger_order": [x for x in (j.get("ledger_order") or LEDGER_ORDER) if x in doc["ledgers"]]}


def esc(s: str) -> str:
    return html.escape(s or "", quote=True)


def slug(name: str) -> str:
    s = re.sub(r"[.'’]", "", name.lower())
    return re.sub(r"[^a-z0-9]+", "-", s).strip("-")


def place_name(county: str, unit: str) -> str:
    """'Alachua County', 'East Baton Rouge Parish'; an independent city keeps its own name."""
    return county if county.endswith(" City") else f"{county} {unit}"


def app_page(st: str) -> str:
    return "/index.html" if st == "FL" else f"/{st.lower()}.html"


def url_for(rel: str) -> str:
    return f"{SITE}{rel}"


def verified(a: dict) -> bool:
    return (a.get("status") == "VERIFIED" and (a.get("source_url") or "").startswith("https://")
            and bool(a.get("answer")) and bool(a.get("verified_on")))


def ledger_answers(entry: dict | None) -> dict[str, dict]:
    return {a["q"]: a for a in (entry or {}).get("answers", []) if a.get("q")}


def county_has_verified(cdata: dict) -> bool:
    return any(verified(a) for L in cdata.values() for a in (L or {}).get("answers", []))


def merged(state: dict, ledger: str, county: str | None) -> dict[str, tuple[dict, str]]:
    """question id -> (answer, scope) with a county answer replacing the statewide one in that county."""
    out = {q: (a, "state") for q, a in ledger_answers(state["ledgers"].get(ledger)).items()}
    if county:
        for q, a in ledger_answers(state.get("counties", {}).get(county, {}).get(ledger)).items():
            out[q] = (a, "county")
    return out


