def plan_counties(doc: dict) -> dict[str, list[str]]:
    plan = {}
    for st, state in doc["states"].items():
        cs = sorted((c for c, cd in state.get("counties", {}).items() if county_has_verified(cd)), key=str.lower)
        slugs = [slug(c) for c in cs]
        if len(slugs) != len(set(slugs)) or "index" in slugs:
            raise SystemExit(f"county slug collision in {st}")
        plan[st] = cs
    return plan


def build() -> dict[Path, str]:
    doc = json.loads(GUIDE_JSON.read_text(encoding="utf-8"))
    plan = plan_counties(doc)
    files: dict[Path, str] = {OUT_DIR / "guides.css": CSS, OUT_DIR / "index.html": index_page(doc, plan)}
    for st, counties in plan.items():
        state = doc["states"][st]
        files[OUT_DIR / st.lower() / "index.html"] = state_page(doc, st, state, counties)
        for c in counties:
            files[OUT_DIR / st.lower() / f"{slug(c)}.html"] = county_page(doc, st, state, c)
    files[SITEMAP] = sitemap(SITEMAP.read_text(encoding="utf-8"), guide_urls(plan))
    return files


def guide_urls(plan: dict[str, list[str]]) -> list[str]:
    urls = [url_for("/guides/")]
    for st in sorted(plan):
        urls.append(url_for(f"/guides/{st.lower()}/"))
        urls += [url_for(f"/guides/{st.lower()}/{slug(c)}") for c in plan[st]]
    return urls


def sitemap(text: str, urls: list[str]) -> str:
    block = START + "\n" + "".join(
        f"  <url><loc>{esc(u)}</loc><changefreq>monthly</changefreq><priority>0.6</priority></url>\n" for u in urls
    ) + "  " + END
    if START in text:
        return re.sub(re.escape(START) + r".*?" + re.escape(END), lambda _m: block, text, flags=re.S)
    return text.replace("</urlset>", "  " + block + "\n</urlset>")


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--check", action="store_true", help="fail if any output is out of date")
    args = ap.parse_args()
    files = build()
    expected = {p for p in files if p.parent == OUT_DIR or OUT_DIR in p.parents}
    stale_extra = [p for p in OUT_DIR.rglob("*") if p.is_file() and p not in expected] if OUT_DIR.exists() else []
    if args.check:
        bad = [str(p.relative_to(REPO)) for p, t in files.items()
               if not p.exists() or p.read_text(encoding="utf-8") != t]
        bad += [f"{p.relative_to(REPO)} (not generated)" for p in stale_extra]
        if bad:
            print("out of date - run scripts/build_public_guides.py:\n  " + "\n  ".join(sorted(bad)))
            return 1
        print(f"guides up to date ({len(expected)} files)")
        return 0
    for p in stale_extra:
        p.unlink()
    for p, t in files.items():
        p.parent.mkdir(parents=True, exist_ok=True)
        if not p.exists() or p.read_text(encoding="utf-8") != t:
            p.write_text(t, encoding="utf-8")
    print(f"wrote {len(expected)} guide files and the sitemap section")
    return 0


if __name__ == "__main__":
    sys.exit(main())
