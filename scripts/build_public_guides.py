def crumbs(items: list[tuple[str, str]]) -> str:
    lis = "".join(f'<li><a href="{esc(h)}">{esc(t)}</a></li>' if h else f'<li aria-current="page">{esc(t)}</li>'
                  for t, h in items)
    return f'<nav class="g-crumbs" aria-label="Breadcrumb"><ol>{lis}</ol></nav>\n'


def breadcrumb_ld(items: list[tuple[str, str]]) -> dict:
    return {"@context": "https://schema.org", "@type": "BreadcrumbList", "itemListElement": [
        {"@type": "ListItem", "position": i + 1, "name": t, "item": url_for(h)} for i, (t, h) in enumerate(items)]}


def page_ld(kind: str, title: str, description: str, rel: str, modified: str) -> dict:
    return {"@context": "https://schema.org", "@type": kind, "headline" if kind == "Article" else "name": title,
            "description": description, "url": url_for(rel), "dateModified": modified, "inLanguage": "en-US",
            "publisher": {"@type": "Organization", "name": BRAND, "url": SITE + "/"}}


