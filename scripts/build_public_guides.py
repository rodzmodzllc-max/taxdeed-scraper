def answer_html(q: dict, a: dict, scope: str, unit: str, county_page: bool) -> str:
    """One VERIFIED answer. The STATEWIDE chip appears only where a statewide answer stands in on a county page."""
    scope_tag = ' <span class="g-scope">Statewide</span>' if (county_page and scope != "county") else ""
    parts = [f'<article class="g-answer"><h4>{esc(q["question"])}{scope_tag}</h4>', f"<p>{esc(a['answer'])}</p>"]
    if a.get("quote"):
        caps = " g-caps" if mostly_caps(a["quote"]) else ""
        parts.append(f'<details class="g-src"><summary>Official wording</summary>'
                     f'<blockquote class="g-quote{caps}">“{esc(a["quote"])}”</blockquote></details>')
    meta = [f'Source: <a href="{esc(a["source_url"])}" rel="noopener" referrerpolicy="origin">'
            f'{esc(a.get("source_title") or "Official page")}</a>']
    if a.get("citation"):
        meta.append(esc(a["citation"]))
    if a.get("office"):
        meta.append(esc(a["office"]))
    meta.append(f'Checked <time datetime="{esc(a["verified_on"])}">{esc(fmt_date(a["verified_on"]))}</time>')
    parts.append(f'<p class="g-meta">{" · ".join(meta)}</p></article>')
    return "\n".join(parts)


def open_line(q: dict, a: dict | None, unit_word: str) -> str:
    if a and a.get("status") == "SOURCE_RESTRICTED":
        why = f"The official page could not be read automatically - check it directly with the {unit_word} office."
    else:
        why = f"Not yet verified - check with the {unit_word} office."
    return f'<li>{esc(q["question"])}<span>{esc(why)}</span></li>'


def ledger_section(doc: dict, state: dict, ledger: str, county: str | None) -> tuple[str, list[str], tuple[int, int]]:
    """The ledger's block, or '' when it has no verified answer; also the verified dates shown and
    (answered, total) for the table of contents. Questions follow the journey steps."""
    ans = merged(state, ledger, county)
    questions = doc["questions"][ledger]
    is_v = lambda q: q["id"] in ans and verified(ans[q["id"]][0])  # noqa: E731
    shown = [(q, *ans[q["id"]]) for q in questions if is_v(q)]
    if not shown:
        return "", [], (0, len(questions))
    unit_word = state["unit"].lower()
    name = doc["ledgers"][ledger]
    j = journey(doc)
    qmap = j["map"].get(ledger, {})
    steps = list(j["steps"])
    if any(qmap.get(q["id"]) not in {s["id"] for s in steps} for q in questions):
        steps.append({"id": "more", "label": "More", "title": "More questions"})
    out = [f'<section class="g-ledger" data-ledger="{ledger}" id="l-{ledger.lower()}" aria-labelledby="l-{ledger.lower()}-h">',
           f'<h2 id="l-{ledger.lower()}-h">{esc(name)} <span class="g-count">{len(shown)} of {len(questions)} answered</span></h2>']
    summary = (state["ledgers"].get(ledger) or {}).get("summary")
    if summary and not SUMMARY_SKIP.search(summary):
        out.append(f'<p class="g-summary">{esc(summary)}</p>')
    n = 0
    for st in steps:
        in_step = [q for q in questions if (qmap.get(q["id"]) if qmap.get(q["id"]) in {s["id"] for s in j["steps"]}
                                           else "more") == st["id"]]
        if not in_step:
            continue
        n += 1
        out.append(f'<h3 class="g-step">Step {n} · {esc(st["label"])} <span>{esc(st["title"])}</span></h3>')
        out += [answer_html(q, ans[q["id"]][0], ans[q["id"]][1], unit_word, county is not None) for q in in_step if is_v(q)]
        rest = [open_line(q, ans.get(q["id"], (None, ""))[0], unit_word) for q in in_step if not is_v(q)]
        if rest:
            out.append('<ul class="g-open">' + "".join(rest) + "</ul>")
    out.append("</section>")
    return "\n".join(out), [a["verified_on"] for _, a, _ in shown], (len(shown), len(questions))


def toc(doc: dict, items: list[tuple[str, tuple[int, int]]]) -> str:
    lis = "".join(f'<li><a href="#l-{L.lower()}" data-ledger="{L}"><span class="g-toc-name">{esc(doc["ledgers"][L])}</span>'
                  f'<span class="g-toc-n">{n} of {m} answered</span></a></li>' for L, (n, m) in items)
    return f'<nav class="g-toc" aria-label="On this page"><p class="g-toc-h">On this page</p><ol>{lis}</ol></nav>\n'


def ledger_blocks(doc: dict, state: dict, county: str | None):
    """(sections, dates, toc items) in the journey's ledger order."""
    sections, dates, items = [], [], []
    for L in journey(doc)["ledger_order"]:
        block, ds, counts = ledger_section(doc, state, L, county)
        if block:
            sections.append(block)
            dates += ds
            items.append((L, counts))
    return sections, dates, items


def with_cta(sections: list[str], cta_html: str) -> list[str]:
    """The call to action follows the first ledger."""
    return sections[:1] + [cta_html] + sections[1:] if sections else [cta_html]


def cta(state_name: str, place: str | None, st: str) -> str:
    where = place or state_name
    return f"""<section class="g-cta" aria-labelledby="g-cta-h">
<h2 id="g-cta-h">See what is listed in {esc(where)}</h2>
<p>TAXACQ shows each listing with its official source, when that source was last read, and the office's own process for acquiring it. Accounts are free while TAXACQ is in beta.</p>
<a class="g-primary" href="/index.html">Create a free account</a>
<a class="g-secondary" href="{esc(app_page(st))}">See current listings in {esc(where)}</a>
</section>
"""


