#!/usr/bin/env python3
"""Counts-only dry run of the inventory-status rule over the production gap
(data/current_state/inventory-status-gap-<date>.json: every row outside
Florida that had no inventory_status, grouped by what the rule reads).

The groups were exported read-only; this script writes no database row. It
replays harvesters/governance/inventory_status.status_for_row over each
group and reports, per state and source, how many rows the rule now maps
and to which status - the before/after the PR claims. `--check` fails
when the committed report is not what the current rule produces.

    python3 scripts/inventory_status_gap_report.py            # rewrite the report
    python3 scripts/inventory_status_gap_report.py --check    # CI / test pin
"""
from __future__ import annotations

import argparse
import json
import sys
from collections import defaultdict
from datetime import date
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO))
from harvesters.governance import inventory_status as IS  # noqa: E402

GROUPS = REPO / "data" / "current_state" / "inventory-status-gap-2026-10-11.json"
REPORT = REPO / "docs" / "review" / "inventory-status-dryrun-2026-10-11.md"
TODAY = date(2026, 10, 11)   # the export date: a sale date is judged against it, never against the clock


def row_of(g: dict) -> dict:
    """A representative row for one group: exactly the columns the rule reads."""
    row = {"state": g["state"], "source": g["source"], "source_id": g["source_id"], "status": g["status"],
           "inventory_status_raw": g.get("raw"), "inventory_type": g.get("inventory_type"), "inventory_status": None,
           "otc_provenance": {"adapter": g["adapter"]} if g.get("adapter") else None}
    if g.get("has_sale_date"):
        row["sale_date"] = "2026-12-01"     # a date ahead of the export date; the group holds dates, not values
    if g.get("list_date"):
        row["list_as_of"] = g["list_date"]   # the list's own published date (LA 2024-02-27, PA 2025-10-07)
    if g.get("tx_sale_status"):
        row["tx_sale_status"] = g["tx_sale_status"]   # LGBS's own sale-status wording, verbatim
    if g.get("has_result"):
        row["result_amount"] = 1
    return row


def replay(groups: list[dict], today: date) -> dict:
    per_source: dict[tuple[str, str], dict] = {}
    totals = {"rows": 0, "mapped": 0, "unmapped": 0, "by_status": defaultdict(int)}
    for g in groups:
        key = (g["state"], g["source_id"], g["source"])
        ps = per_source.setdefault(key, {"rows": 0, "mapped": 0, "unmapped": 0, "by_status": defaultdict(int), "ledger": g["source"]})
        obs = IS.status_for_row(row_of(g), today=today)
        for d in (ps, totals):
            d["rows"] += g["n"]
            if obs is None:
                d["unmapped"] += g["n"]
            else:
                d["mapped"] += g["n"]
                d["by_status"][f"{obs.status} ({obs.basis})"] += g["n"]
    return {"totals": totals, "per_source": per_source}


def render(data: dict, read_on: str) -> str:
    t = data["totals"]
    lines = [f"# Inventory status: read-only dry run over the production gap ({read_on})", "",
             "Generated by `scripts/inventory_status_gap_report.py` from `data/current_state/inventory-status-gap-"
             f"{read_on}.json` - a counts-only export of every `properties` row outside Florida whose "
             "`inventory_status` was NULL (read-only SQL, no row written). The rule replayed is "
             "`harvesters/governance/inventory_status.status_for_row` as committed; before this change every one "
             "of these rows was unmapped (the writer's `adapter_record_status` maps auction / certificate rows only, "
             "Louisiana was excluded by state, and Texas RealAuction had no rule).", "",
             "| | Rows |", "|---|---|",
             f"| Rows with no inventory_status (before) | {t['rows']:,} |",
             f"| Mapped by the rule now (after, at the next writer run) | {t['mapped']:,} |",
             f"| Still unmapped | {t['unmapped']:,} |", "",
             "By status the rule assigns:", "", "| Status (basis) | Rows |", "|---|---|"]
    for k, n in sorted(t["by_status"].items(), key=lambda kv: -kv[1]):
        lines.append(f"| {k} | {n:,} |")
    lines += ["", "## By state and source", "", "| State | Source | Ledger | Rows | Mapped | Statuses |", "|---|---|---|---|---|---|"]
    for (st, sid, _ledger), d in sorted(data["per_source"].items()):
        statuses = "; ".join(f"{k} {n:,}" for k, n in sorted(d["by_status"].items(), key=lambda kv: -kv[1])) or "-"
        lines.append(f"| {st} | {sid} | {d['ledger']} | {d['rows']:,} | {d['mapped']:,} | {statuses} |")
    lines += ["", "`available_otc` is asserted only where the source's own wording for the row is one of its published "
              "offered wordings (`AVAILABLE_OFFERED_WORDINGS`); every other listed row is `active` on list presence, "
              "with a dated list named in its basis. No row is closed, sold or re-statused by this change; the status "
              "is written by the existing gated writer at its next run, and absence from a list is `closed`, never a result.", ""]
    return "\n".join(lines)


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args(argv)
    src = json.loads(GROUPS.read_text(encoding="utf-8"))
    text = render(replay(src["groups"], TODAY), src["read_on"])
    if args.check:
        current = REPORT.read_text(encoding="utf-8") if REPORT.exists() else ""
        if current != text:
            print(f"{REPORT.relative_to(REPO)} is stale - run scripts/inventory_status_gap_report.py")
            return 1
        print("inventory status dry run is current")
        return 0
    REPORT.write_text(text, encoding="utf-8")
    print(f"wrote {REPORT.relative_to(REPO)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
